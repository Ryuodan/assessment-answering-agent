"""Generate the documents in docs/generated/. Never edit those files by hand.

    uv run poe gen

- `openapi.json`: the HTTP API contract, from the FastAPI app. Verified on
  2026-10-05 to be identical under different settings, so `.env` does not
  leak into it.
- `layers.md`: the layers of src/ from harness/layers.toml, each module with
  the first paragraph of its docstring, and the exceptions allowed today.
- `api.md`: every HTTP operation, grouped by path, with the first paragraph of
  its route's docstring (or the summary FastAPI derives from its name).
- `errors.md`: every error class and code a response can carry.
- `settings.md`: every setting, its environment variable, type, default and
  the comment above it, read from the syntax tree of src/config.py, so the
  catalogue never imports the module (which would read the real .env) and
  defaults appear as written in the source rather than as machine paths.

`tests/harness/test_generated.py` fails when a file here is stale.
"""

from __future__ import annotations

import ast
import json
import sys
from pathlib import Path
from typing import TYPE_CHECKING

from harness.report import ROOT

if TYPE_CHECKING:
    from src.errors import AppError

GENERATED = ROOT / "docs" / "generated"
CONFIG = ROOT / "src" / "config.py"


def openapi_json() -> str:
    from src.api import app

    return json.dumps(app.openapi(), indent=2, ensure_ascii=False) + "\n"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _default_of(value: ast.expr | None, source: str) -> str:
    if value is None:
        return "(required)"
    if isinstance(value, ast.Call) and getattr(value.func, "id", "") == "Field":
        for keyword in value.keywords:
            if keyword.arg == "default":
                return ast.get_source_segment(source, keyword.value) or ""
        if value.args:
            return ast.get_source_segment(source, value.args[0]) or ""
        return "(required)"
    return ast.get_source_segment(source, value) or ""


def _description_of(value: ast.expr | None) -> str:
    if isinstance(value, ast.Call) and getattr(value.func, "id", "") == "Field":
        for keyword in value.keywords:
            if keyword.arg == "description" and isinstance(keyword.value, ast.Constant):
                return str(keyword.value.value)
    return ""


def settings_md(config: Path = CONFIG) -> str:
    source = config.read_text(encoding="utf-8")
    lines = source.splitlines()
    tree = ast.parse(source)
    settings = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "Settings")

    out = [
        "# Settings",
        "",
        "<!-- Generated by `uv run poe gen` from src/config.py. Do not edit by hand. -->",
        "",
        "Every setting the application reads, as declared in `src/config.py`. Each is",
        "set through the environment or `.env` under its upper-case name; `.env.example`",
        "lists them all (enforced by ARCH-ENVEX). Defaults are shown as written in the",
        "source. The description is the comment above the field, the field's",
        "`description`, or the docstring under it.",
        "",
    ]
    section = ""
    rows: list[str] = []

    def flush() -> None:
        if rows:
            out.extend(["| Variable | Type | Default | Description |", "|---|---|---|---|", *rows, ""])
            rows.clear()

    body = settings.body
    for index, stmt in enumerate(body):
        if not (isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name)):
            continue
        name = stmt.target.id
        if name == "model_config":
            continue
        # The comment block directly above the field; a "# --- Title ---" line starts a section.
        comments: list[str] = []
        cursor = stmt.lineno - 2
        while cursor >= 0 and lines[cursor].strip().startswith("#"):
            comments.insert(0, lines[cursor].strip().lstrip("#").strip())
            cursor -= 1
        headings = [c for c in comments if c.startswith("---")]
        if headings:
            flush()
            section = headings[-1].strip("- ").strip()
            out.extend([f"## {section}", ""])
        prose = [c for c in comments if c and not c.startswith("---")]
        description = " ".join(prose) or _description_of(stmt.value)
        if not description and index + 1 < len(body):
            following = body[index + 1]
            if isinstance(following, ast.Expr) and isinstance(following.value, ast.Constant):
                description = str(following.value.value).strip().split("\n\n")[0]
        annotation = ast.get_source_segment(source, stmt.annotation) or ""
        rows.append(
            f"| `{name.upper()}` | `{_cell(annotation)}` | `{_cell(_default_of(stmt.value, source))}` "
            f"| {_cell(description)} |"
        )
    flush()
    return "\n".join(out).rstrip() + "\n"


def _first_paragraph(text: str | None) -> str:
    return _cell((text or "").strip().split("\n\n")[0])


def layers_md() -> str:
    """The layers of src/ as harness/layers.toml defines them, with the exceptions allowed today."""
    import tomllib

    from harness.layers import LAYERS_FILE, Layering, src_modules

    layering = Layering.load(LAYERS_FILE)
    files = src_modules(ROOT)
    allow = tomllib.loads((ROOT / "harness" / "arch-allowlist.toml").read_text(encoding="utf-8"))
    out = [
        "# Layers",
        "",
        "<!-- Generated by `uv run poe gen` from harness/layers.toml. Do not edit by hand. -->",
        "",
        "The layers of `src/`, lowest first. A module may import modules of its own layer and of any layer",
        "below it (ARCH-LAYER), and an owned library only from the layers that own it (ARCH-OWNER). Why the",
        "lines are drawn here: [ARCHITECTURE.md](../../ARCHITECTURE.md#layers).",
        "",
    ]
    for number, layer in enumerate(layering.order, start=1):
        modules = sorted(m for m, owner in layering.exact.items() if owner == layer)
        modules += sorted(f"{prefix}.*" for prefix, owner in layering.prefixes.items() if owner == layer)
        owned = sorted(lib for lib, allowed in layering.owners.items() if layer in allowed)
        out += [f"## {number}. {layer}", "", layering.about.get(layer, ""), ""]
        out.append("- **Modules:** " + ", ".join(f"`{m}`" for m in modules))
        if owned:
            out.append("- **Owns:** " + ", ".join(f"`{lib}`" for lib in owned))
        out += ["", "| Module | What it is |", "|---|---|"]
        for name, path in sorted(files.items()):
            if layering.layer_of(name) == layer:
                doc = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8")))
                out.append(f"| `{path.relative_to(ROOT).as_posix()}` | {_first_paragraph(doc)} |")
        out.append("")
    single = sorted(
        (lib, sorted(allowed)) for lib, allowed in layering.owners.items() if not allowed & set(layering.order)
    )
    if single:
        out += ["## Owned by one module", ""]
        out += [f"- `{lib}`: {', '.join(f'`{m}`' for m in modules)}" for lib, modules in single]
        out.append("")
    out += [
        "## Exceptions allowed today",
        "",
        "Each is on `harness/arch-allowlist.toml` against a tech-debt item, and may only be removed.",
        "",
        "| Rule | Module | Imports | Debt |",
        "|---|---|---|---|",
    ]
    out += [f"| ARCH-LAYER | `{e['module']}` | `{e['imports']}` | {e['debt']} |" for e in allow.get("layer", [])]
    out += [f"| ARCH-OWNER | `{e['module']}` | `{e['library']}` | {e['debt']} |" for e in allow.get("owner", [])]
    return "\n".join(out).rstrip() + "\n"


def error_codes() -> tuple[list[type[AppError]], list[tuple[str, str, str]]]:
    """Every AppError class, and every (code, class, where) a raise site names itself."""
    import ast

    from src import errors

    classes: list[type[AppError]] = []
    pending: list[type[AppError]] = [errors.AppError]
    while pending:
        cls = pending.pop()
        if cls in classes:  # a class with two parents in the hierarchy is reached twice
            continue
        classes.append(cls)
        pending.extend(cls.__subclasses__())
    by_name = {cls.__name__: cls for cls in classes}

    sites: list[tuple[str, str, str]] = []
    for path in sorted((ROOT / "src").rglob("*.py")):
        module = path.relative_to(ROOT).with_suffix("").as_posix().removesuffix("/__init__").replace("/", ".")
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for function in ast.walk(tree):
            if not isinstance(function, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for node in ast.walk(function):
                if not isinstance(node, ast.Call):
                    continue
                name = node.func.attr if isinstance(node.func, ast.Attribute) else getattr(node.func, "id", "")
                code = next(
                    (k.value.value for k in node.keywords if k.arg == "code" and isinstance(k.value, ast.Constant)),
                    None,
                )
                if name in by_name and isinstance(code, str):
                    sites.append((code, name, f"{module}.{function.name}"))
    return classes, sorted(set(sites))


def errors_md() -> str:
    """The error catalogue: every class and every code a response can carry."""
    classes, sites = error_codes()
    out = [
        "# Errors",
        "",
        "<!-- Generated by `uv run poe gen` from src/errors.py and the raise sites in src/. Do not edit by hand. -->",
        "",
        'Every error response from the API is `{"detail": <message>, "code": <code>}`. The message is written',
        "for a person and may change; the code is stable. Classes are defined in `src/errors.py` (plan 004, D-013).",
        "",
        "## Classes",
        "",
        "| Class | Status | Default code | Meaning |",
        "|---|---|---|---|",
    ]
    for cls in sorted(classes, key=lambda c: (c.status, c.__mro__[1].__name__ != "AppError", c.__name__)):
        meaning = (cls.__doc__ or "").strip().splitlines()[0] if cls.__doc__ else ""
        out.append(f"| `{cls.__name__}` | {cls.status} | `{cls.code}` | {meaning} |")
    out += [
        "",
        "## Codes named where they are raised",
        "",
        "| Code | Status | Raised as | Where |",
        "|---|---|---|---|",
    ]
    status_of = {cls.__name__: cls.status for cls in classes}
    grouped: dict[tuple[str, str], list[str]] = {}
    for code, name, where in sites:
        grouped.setdefault((code, name), []).append(where)
    for (code, name), places in sorted(grouped.items()):
        out.append(f"| `{code}` | {status_of[name]} | `{name}` | {', '.join(f'`{p}`' for p in places)} |")
    out += [
        "",
        "## From the framework",
        "",
        "| Code | Status | When |",
        "|---|---|---|",
        "| `route_not_found` | 404 | no route matches the path |",
        "| `method_not_allowed` | 405 | the route exists, the method does not |",
        "| `validation_failed` | 422 | a body or parameter does not match its model; `detail` is FastAPI's list |",
        "| `internal_error` | 500 | anything unexpected; the detail is in the server log |",
    ]
    return "\n".join(out) + "\n"


def api_md() -> str:
    """Every HTTP operation, grouped by the first part of its path, with what it does."""
    from src.api import app

    out = [
        "# HTTP API",
        "",
        "<!-- Generated by `uv run poe gen` from the FastAPI app. Do not edit by hand. -->",
        "",
        "Every operation the server offers, grouped by path. Each is described by the first paragraph of its",
        "route's docstring; one without a docstring shows the summary FastAPI derives from the function's name.",
        "Request and response shapes are in [openapi.json](openapi.json); a running server serves them at `/docs`.",
        "Errors: [errors.md](errors.md).",
        "",
    ]
    groups: dict[str, list[str]] = {}
    for path, operations in app.openapi()["paths"].items():
        parts = path.strip("/").split("/")
        group = "/" + "/".join(parts[:2] if parts[0] == "api" else parts[:1])
        for method, operation in operations.items():
            what = _first_paragraph(operation.get("description")) or _cell(operation.get("summary", ""))
            groups.setdefault(group, []).append(f"| `{method.upper()}` | `{path}` | {what} |")
    for group, rows in groups.items():
        out += [f"## `{group}`", "", "| Method | Path | What it does |", "|---|---|---|", *rows, ""]
    return "\n".join(out).rstrip() + "\n"


def documents() -> dict[Path, str]:
    """Every generated document and what it should contain now."""
    return {
        GENERATED / "openapi.json": openapi_json(),
        GENERATED / "settings.md": settings_md(),
        GENERATED / "layers.md": layers_md(),
        GENERATED / "errors.md": errors_md(),
        GENERATED / "api.md": api_md(),
    }


def main() -> int:
    GENERATED.mkdir(parents=True, exist_ok=True)
    for path, content in documents().items():
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
