"""Generate the documents in docs/generated/. Never edit those files by hand.

    uv run poe gen

- `openapi.json`: the HTTP API contract, from the FastAPI app. Verified on
  2026-10-05 to be identical under different settings, so `.env` does not
  leak into it.
- `settings.md`: every setting, its environment variable, type, default and
  the comment above it, read from the syntax tree of src/config.py, so the
  catalogue never imports the module (which would read the real .env) and
  defaults appear as written in the source rather than as machine paths.

`tests/harness/test_generated.py` fails when a file here is stale.
"""

from __future__ import annotations

import ast
import json
import sys
from pathlib import Path

from harness.report import ROOT

GENERATED = ROOT / "docs" / "generated"
CONFIG = ROOT / "src" / "config.py"


def openapi_json() -> str:
    from src.api import app

    return json.dumps(app.openapi(), indent=2, ensure_ascii=False) + "\n"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _default_of(value: ast.expr | None, source: str) -> str:
    if value is None:
        return "(required)"
    if isinstance(value, ast.Call) and getattr(value.func, "id", "") == "Field":
        for keyword in value.keywords:
            if keyword.arg == "default":
                return ast.get_source_segment(source, keyword.value) or ""
        if value.args:
            return ast.get_source_segment(source, value.args[0]) or ""
        return "(required)"
    return ast.get_source_segment(source, value) or ""


def _description_of(value: ast.expr | None) -> str:
    if isinstance(value, ast.Call) and getattr(value.func, "id", "") == "Field":
        for keyword in value.keywords:
            if keyword.arg == "description" and isinstance(keyword.value, ast.Constant):
                return str(keyword.value.value)
    return ""


def settings_md(config: Path = CONFIG) -> str:
    source = config.read_text(encoding="utf-8")
    lines = source.splitlines()
    tree = ast.parse(source)
    settings = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "Settings")

    out = [
        "# Settings",
        "",
        "<!-- Generated by `uv run poe gen` from src/config.py. Do not edit by hand. -->",
        "",
        "Every setting the application reads, as declared in `src/config.py`. Each is",
        "set through the environment or `.env` under its upper-case name; `.env.example`",
        "lists them all (enforced by ARCH-ENVEX). Defaults are shown as written in the",
        "source. The description is the comment above the field, the field's",
        "`description`, or the docstring under it.",
        "",
    ]
    section = ""
    rows: list[str] = []

    def flush() -> None:
        if rows:
            out.extend(["| Variable | Type | Default | Description |", "|---|---|---|---|", *rows, ""])
            rows.clear()

    body = settings.body
    for index, stmt in enumerate(body):
        if not (isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name)):
            continue
        name = stmt.target.id
        if name == "model_config":
            continue
        # The comment block directly above the field; a "# --- Title ---" line starts a section.
        comments: list[str] = []
        cursor = stmt.lineno - 2
        while cursor >= 0 and lines[cursor].strip().startswith("#"):
            comments.insert(0, lines[cursor].strip().lstrip("#").strip())
            cursor -= 1
        headings = [c for c in comments if c.startswith("---")]
        if headings:
            flush()
            section = headings[-1].strip("- ").strip()
            out.extend([f"## {section}", ""])
        prose = [c for c in comments if c and not c.startswith("---")]
        description = " ".join(prose) or _description_of(stmt.value)
        if not description and index + 1 < len(body):
            following = body[index + 1]
            if isinstance(following, ast.Expr) and isinstance(following.value, ast.Constant):
                description = str(following.value.value).strip().split("\n\n")[0]
        annotation = ast.get_source_segment(source, stmt.annotation) or ""
        rows.append(
            f"| `{name.upper()}` | `{_cell(annotation)}` | `{_cell(_default_of(stmt.value, source))}` "
            f"| {_cell(description)} |"
        )
    flush()
    return "\n".join(out).rstrip() + "\n"


def documents() -> dict[Path, str]:
    """Every generated document and what it should contain now."""
    return {
        GENERATED / "openapi.json": openapi_json(),
        GENERATED / "settings.md": settings_md(),
    }


def main() -> int:
    GENERATED.mkdir(parents=True, exist_ok=True)
    for path, content in documents().items():
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
