def show(name, text, chunk_size=1800):
    print("=" * 78)
    print(name)
    print("=" * 78)
    blocks = parse_blocks(text)
    kinds = {}
    for block in blocks:
        kinds[block.kind] = kinds.get(block.kind, 0) + 1
    print(f"  blocks: {kinds}")
    for chunk in chunk_document(text, source_name="doc.pdf", chunk_size=chunk_size):
        meta = chunk.metadata
        span = meta["clause_start"]
        if meta["clause_end"] and meta["clause_end"] != span:
            span = f"{span}-{meta['clause_end']}"
        print(
            f"  [{meta['chunk']}] {meta['kind']:6} clause={span or '-':12} "
            f"items={meta['item_count']} part={meta['part']}/{meta['parts']} "
            f"doc={meta['doc_id'] or '-'}"
        )
    print()


if __name__ == "__main__":
    for name, text in SHAPES.items():
        show(name, text)
